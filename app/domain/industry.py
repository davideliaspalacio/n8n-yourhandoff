def normalize(value: object) -> str:
    text = str(value or "").lower().replace("&", "and")
    text = re.sub(r"[/,]", " ", text)
    text = re.sub(r"[^a-z0-9 ]", " ", text)
    return re.sub(r"\s+", " ", text).strip()


INDUSTRY_MAP: dict[str, str] = {
    **{v.lower().replace("_", " "): v for v in _HUBSPOT_VALUES},
    **{normalize(k): v for k, v in _ALIASES.items()},
}


def to_hubspot_industry(raw: object) -> str | None:
    key = normalize(raw)
    if not key:
        return None
    if key in INDUSTRY_MAP:
        return INDUSTRY_MAP[key]
    trimmed = re.sub(r"\s+", " ", re.sub(r"\b(services|management|programs)\b", "", key)).strip()
    return INDUSTRY_MAP.get(trimmed)
